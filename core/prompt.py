"""外部から取り込んだ文章を、アプリの指示と混ざらない形でプロンプトに載せる。"""

from __future__ import annotations

import secrets


def data_block(text: str, label: str = "データ") -> str:
    """外部由来の文章を境界マーカーで囲む。

    囲いに使う印を毎回変えるのが要点。``` のような決まった印で囲むと、
    取り込んだ文書の中に同じ印を1行書いておくだけで囲いから抜け出せてしまい、
    その先に書いた文がアプリからの指示のように見えてしまう。
    毎回変わる合言葉なら、文書を用意する側には前もって知りようがない。

    これは注入を完全に防ぐものではなく、成立しにくくするための措置である。
    最後の砦は「出力を人が読んでから使う」こと。
    """
    nonce = secrets.token_hex(4)
    return (
        f"----BEGIN {label} {nonce}----\n"
        f"{text}\n"
        f"----END {label} {nonce}----"
    )
